#!/bin/sh
# Builds, with the Android SDK directly (no Gradle, no libraries):
#   out/quiettv.apk        the home screen, for the TV
#   out/quiettv-setup.apk  QuietTV Setup, the phone app that sets up a TV over Wi-Fi
# Needs: Java 17+ and the Android SDK with platforms;android-34 and build-tools;34.0.0 (or newer).
#   macOS: brew install openjdk@17 && brew install --cask android-commandlinetools
#          sdkmanager "platforms;android-34" "build-tools;34.0.0"
set -e
cd "$(dirname "$0")"

if [ -z "$JAVA_HOME" ]; then
  for j in /opt/homebrew/opt/openjdk@17 /usr/local/opt/openjdk@17 /usr/lib/jvm/java-17-openjdk-amd64 /usr/lib/jvm/java-17-openjdk; do
    [ -d "$j" ] && JAVA_HOME=$j && break
  done
fi
[ -n "$JAVA_HOME" ] && export PATH="$JAVA_HOME/bin:$PATH"
java -version 2>&1 | grep -qE 'version "(1[7-9]|[2-9][0-9])' || { echo "Java 17 or newer is needed (set JAVA_HOME)." >&2; exit 1; }

SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}
[ -n "$SDK" ] || for d in "$HOME/Library/Android/sdk" /opt/homebrew/share/android-commandlinetools "$HOME/Android/Sdk"; do
  [ -d "$d/platforms/android-34" ] && SDK=$d && break
done
JAR=$SDK/platforms/android-34/android.jar
BT=$(ls -d "$SDK"/build-tools/3[4-9]* 2>/dev/null | sort -V | tail -1)
[ -f "$JAR" ] && [ -n "$BT" ] || { echo "Android SDK not found: set ANDROID_HOME and install platforms;android-34 and build-tools;34.0.0." >&2; exit 1; }

# One version for both apps, from the home screen's manifest.
VC=$(sed -n 's/.*android:versionCode="\([0-9]*\)".*/\1/p' app/AndroidManifest.xml | head -1)
VN=$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' app/AndroidManifest.xml | head -1)

# The signing key is made on the first build. Keep it: updates must be signed with the same key.
# (Releases are signed in CI with the release key: KEYSTORE and KEYSTORE_PASS.)
KS=${KEYSTORE:-quiettv.jks}
PASS=${KEYSTORE_PASS:-quiettv-local}
[ -f "$KS" ] || keytool -genkeypair -keystore "$KS" -storepass "$PASS" -keypass "$PASS" -alias quiettv \
  -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=QuietTV" >/dev/null 2>&1

rm -rf out
mkdir -p out

# apk <name> <manifest> <res dir> <source dirs...>
apk() {
  name=$1; manifest=$2; res=$3; shift 3
  w=out/build-$name
  mkdir -p "$w/res" "$w/classes" "$w/dex" "$w/gen"
  "$BT/aapt2" compile --dir "$res" -o "$w/res/"
  "$BT/aapt2" link -o "$w/base.apk" -I "$JAR" --manifest "$manifest" --java "$w/gen" \
    --min-sdk-version 26 --target-sdk-version 34 --version-code "$VC" --version-name "$VN" "$w"/res/*.flat
  # File lists are split into arguments on purpose (no paths here contain spaces).
  # shellcheck disable=SC2046
  javac -nowarn -Xlint:-options -encoding UTF-8 -source 8 -target 8 \
    -bootclasspath "$JAR" -cp "$BT/core-lambda-stubs.jar" -d "$w/classes" $(find "$@" "$w/gen" -name '*.java')
  # shellcheck disable=SC2046
  "$BT/d8" --min-api 26 --release --lib "$JAR" --output "$w/dex" $(find "$w/classes" -name '*.class')
  cp "$w/base.apk" "$w/unsigned.apk"
  (cd "$w/dex" && zip -q ../unsigned.apk classes.dex)
  "$BT/zipalign" -f 4 "$w/unsigned.apk" "$w/aligned.apk"
  "$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$PASS" --out "out/$name.apk" "$w/aligned.apk"
  echo "Built out/$name.apk ($(wc -c < "out/$name.apk" | tr -d ' ') bytes, version $VN)"
}

# The home screen, for the TV.
apk quiettv app/AndroidManifest.xml app/res app/src

# QuietTV Setup, for the phone. It shares the logo, and its lists come from lists/*.txt, so the phone
# app and quiettv.sh always agree on what's safe and what's protected.
mkdir -p out/setup-res out/setup-gen/com/quiettv/setup
cp -R setup-app/res/. out/setup-res/
mkdir -p out/setup-res/drawable
cp app/res/drawable/ic_logo.xml app/res/drawable/ic_launcher_bg.xml app/res/drawable/ic_launcher_fg.xml out/setup-res/drawable/
cp -R app/res/mipmap-anydpi-v26 out/setup-res/
{
  echo "package com.quiettv.setup;"
  echo "/** Generated by build.sh from lists/safe.txt and lists/protected.txt. */"
  echo "final class Lists {"
  echo "    static final class Safe {"
  echo "        final String pkg, what;"
  echo "        final boolean junk;"
  echo "        Safe(String pkg, boolean junk, String what) { this.pkg = pkg; this.junk = junk; this.what = what; }"
  echo "    }"
  echo "    private static final Safe[] SAFE_LIST = {"
  grep -v '^[[:space:]]*#' lists/safe.txt | grep '|' | while IFS='|' read -r p kind what; do
    p=$(echo "$p" | tr -d ' '); kind=$(echo "$kind" | tr -d ' ')
    what=$(echo "$what" | sed 's/^ *//; s/ *$//; s/\\/\\\\/g; s/"/\\"/g')
    [ "$kind" = junk ] && j=true || j=false
    echo "        new Safe(\"$p\", $j, \"$what\"),"
  done
  echo "    };"
  echo "    static final java.util.List<Safe> SAFE = java.util.Arrays.asList(SAFE_LIST);"
  echo "    private static final String[] PROTECTED = {"
  grep -v '^[[:space:]]*#' lists/protected.txt | tr -d ' \t\r' | grep -E '^[A-Za-z0-9_.*]+$' | sed 's/.*/        "&",/'
  echo "    };"
  echo "    private static java.util.regex.Pattern all;"
  echo "    static synchronized boolean isProtected(String pkg) {"
  echo "        if (all == null) {"
  echo "            StringBuilder sb = new StringBuilder();"
  printf '%s\n' '            for (String p : PROTECTED) sb.append(sb.length() == 0 ? "" : "|").append(p.replace(".", "\\.").replace("*", ".*"));'
  echo "            all = java.util.regex.Pattern.compile(sb.toString());"
  echo "        }"
  echo "        return all.matcher(pkg).matches();"
  echo "    }"
  echo "}"
} > out/setup-gen/com/quiettv/setup/Lists.java
apk quiettv-setup setup-app/AndroidManifest.xml out/setup-res setup-app/src out/setup-gen
